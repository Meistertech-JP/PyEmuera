"""Legacy development inventory retained for historical regression tests.

For current release metadata use build_release_status.py. This legacy renderer
requires the original development evidence tree, beyond the public source subset.

Run after the test report is written. --check detects stale checked-in metadata.
Registered names, historical heterogeneous rows, archived Oracle comparisons,
and game routes are distinct populations; no combined compatibility rate exists.
"""
from pathlib import Path
import argparse,collections,hashlib,json,sys
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
from pyemuera import __version__
from pyemuera.dispatcher import describe_binding
from pyemuera.builtins import describe_value_binding
from pyemuera.registry import COMMAND_SPECS,FUNCTION_SPECS,SYNTAX_SPECS,fingerprint

def recount(items):
    return dict(sorted(collections.Counter(row['status'] for row in items).items()))

def inventory(test_report, *, allow_incomplete=False):
    if test_report['engine_version']!=__version__:
        raise ValueError('Test report belongs to another engine version')
    incomplete = any(test_report.get(k,0) for k in ('failures','errors','skipped'))
    if incomplete and not allow_incomplete:
        raise ValueError('Only a complete successful test report can be published')
    return {
        'engine_version':__version__,
        'definition_counts':{'commands':len(COMMAND_SPECS),'functions':len(FUNCTION_SPECS),'syntax':len(SYNTAX_SPECS)},
        'unit_tests':test_report['tests'],'unittest_count':test_report['tests'],
        'unit_test_result': {key: test_report.get(key, 0)
                             for key in ('tests', 'failures', 'errors', 'skipped')},
        'full_unit_test_acceptance': not incomplete,
        'artifact_role': ('development_candidate_with_known_failure' if incomplete
                          else 'development_candidate'),
        'test_collection_fingerprint':test_report.get('test_inventory',{}).get('fingerprint'),
        'expression_functions':{n:{'min_arguments':s['min_args'],'max_arguments':s['max_args'],'handler':s['handler']} for n,s in FUNCTION_SPECS.items()},
        'commands':{n:{'family':s['family'],'method_safe':s.get('method_safe')} for n,s in COMMAND_SPECS.items()},
        'runtime_bindings':{n:describe_binding(n) for n in COMMAND_SPECS},
        'expression_runtime_bindings':{n:describe_value_binding(n) for n in FUNCTION_SPECS},
        'language_specs_sha256':fingerprint(),
        'command_family_counts':dict(sorted(collections.Counter(s['family'] for s in COMMAND_SPECS.values()).items())),
        'expression_handler_counts':dict(sorted(collections.Counter(s['handler'] for s in FUNCTION_SPECS.values()).items())),
        'unit_test_evidence':'verification/r45/unit_tests.json',
        'current_evidence_index':'verification/CURRENT_STATUS.json',
        'full_compatibility':False,'formal_a10_release_gate':False,'beta_release_gate':False,
        'new_windows_execution_count':0,
        'windows_verification_policy':'r44_windows_archived_observations; r45_local_fixes_WINDOWS_ACCEPTANCE_PENDING',
        'windows_integration_backlog':'verification/windows_integration_backlog.json',
        'scope':'Registration inventory and current test evidence; neither full-language equivalence nor a combined compatibility rate.'}

def render(root, *, allow_incomplete=False):
    tests=json.loads((root/'verification/r45/unit_tests.json').read_text())
    if hashlib.sha256((root/'PyEmuera.pyz').read_bytes()).hexdigest()!=tests['pyz_sha256']:
        raise ValueError('Tested pyz differs from the current executable')
    from tools.test_inventory import validate_report
    validate_report(root,tests)
    for name in ('SOURCE_AUDIT_1824.json','SOURCE_AUDIT_1824_v24.json'):
        audit=json.loads((root/name).read_text())
        if audit['engine_version']!=__version__ or audit['language_specs_sha256']!=fingerprint():
            raise ValueError('Source audit metadata is stale: '+name)
        for kind,table,key in [('commands',COMMAND_SPECS,'family'),('functions',FUNCTION_SPECS,'handler')]:
            if audit['counts'][kind+'_by_status']!=recount(audit[kind]):
                raise ValueError('Source audit status summary is stale: '+name)
            for row in audit[kind]:
                binding=table[row['name']][key] if row['name'] in table else None
                if row['runtime_family']!=binding:
                    raise ValueError('Source audit binding is stale: '+row['name'])
    old=json.loads((root/'verification/r19/inherited_r18_documents/CAPABILITIES.json').read_text())
    current=inventory(tests, allow_incomplete=allow_incomplete);cap={**old,**current}
    cap['rebuild_note']='Generated by tools/build_status.py from current registry and completed test evidence; --check detects drift.'
    cap['historical_capabilities_snapshot']='verification/r19/inherited_r18_documents/CAPABILITIES.json'
    cap['historical_field_scope']={'a9_delta':'Original a9 change summary, not current test evidence','a10_candidate_delta':'Original early-candidate snapshot, including its Windows-tested flag; current received Windows evidence is indexed separately'}
    cap['received_r36_windows_integration']='verification/r37/received_evidence_integrity.json'
    cap['received_r37_windows_integration']='verification/r38/received_windows_asset_check.json'
    cap['received_r34_windows_integration']='verification/r35/received_evidence_integrity.json'
    cap['received_r32_windows_integration']='verification/r33/received_evidence_integrity.json'
    cap['received_r30_windows_integration' ]='verification/r31/received_evidence_integrity.json'
    cap['received_r20_windows_evidence']='verification/r21/windows_evidence_audit.json'
    cap['received_r19_windows_evidence']='verification/r20/windows_evidence_audit.json'
    cap['rule_display_contract']='verification/r20/source_contract_review.json'
    cap['received_r18_windows_evidence']='verification/r19/windows_evidence_audit.json'
    matrix=json.loads((root/'verification/compatibility_gap_matrix_a10c4.json').read_text())
    counts=recount(matrix['items'])
    if matrix['counts']!=counts or matrix['status_counts']!=counts:raise ValueError('Historical matrix summary drift')
    issue=json.loads((root/'verification/r45/issue_ledger.json').read_text())
    cap['received_r39_windows_integration']='verification/r40/received_r39/R39_WINDOWS_INTEGRATION_RESULTS.json'
    cap['received_r40_windows_integration']='verification/r41/received_r40/R40_WINDOWS_INTEGRATION_RESULTS.json'
    cap['received_r41_windows_integration']='verification/r42/received_r41/R41_WINDOWS_INTEGRATION_RESULTS.json'
    cap['received_r42_windows_integration']='verification/r43/received_r42/R42_WINDOWS_INTEGRATION_RESULTS.json'
    status={
        'schema':'pyemuera-current-status-2','engine_version':__version__,
        'artifact_role':current['artifact_role'],
        'unit_test_result':current['unit_test_result'],
        'full_unit_test_acceptance':current['full_unit_test_acceptance'],
        'final_distribution_acceptance':False,
        'full_compatibility':False,'formal_a10_release_gate':False,'beta_release_gate':False,
        'aggregate_compatibility_rate':None,
        'aggregation_rule':'Do not combine names, contract rows, subcases, launches, test cases or game routes.',
        'implementation_inventory':{'path':'CAPABILITIES.json','commands':len(COMMAND_SPECS),'expression_functions':len(FUNCTION_SPECS),'syntax':len(SYNTAX_SPECS),'language_specs_sha256':fingerprint()},
        'historical_contract_population':{'path':'verification/compatibility_gap_matrix_a10c4.json','rows':len(matrix['items']),'counts':counts,'row_status_changes':0,'current_engine_equivalence':False},
        'evidence_populations':[
            {'kind':'received_windows_native_integration','engine':'r41','path':'verification/r42/received_r41/R41_WINDOWS_INTEGRATION_RESULTS.json','scope':'r41win-20261014-022705; separate native304, language51, analysis14, save16, sort and CLI populations; historical Windows observation, current Python replay indexed separately'},
            {'kind':'received_windows_native_integration','engine':'r42','path':'verification/r43/received_r42/R42_WINDOWS_INTEGRATION_RESULTS.json','scope':'r42run-20261014-120034; archived Windows NLS, Framework, ARRAYMSORT, analysis and selected GUI/input observations; not a new r43 Windows execution'},
            {'kind':'current_internal_unit_regression','path':'verification/r45/unit_tests.json','tests':tests['tests'],'native_comparison':False},
            {'kind':'baseline_vs_current_comparison','path':'R45_COMPATIBILITY_DELTA.json','new_native_execution':False},
            {'kind':'source_contract_and_archived_native_replay','path':'R45_DEVELOPMENT_REPORT_ja.md','new_native_execution':False}],
        'test_collection_fingerprint':tests['test_inventory']['fingerprint'],
        'current_issues':issue,'game_observation_scope':'verification/r45/game_regression.json',
        'new_windows_executions':0,
        'windows_verification_policy':'r44_windows_archived_observations; r45_local_fixes_WINDOWS_ACCEPTANCE_PENDING'}
    return {root/'CAPABILITIES.json':cap,root/'verification/CURRENT_STATUS.json':status}

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true')
    ap.add_argument('--allow-incomplete', action='store_true',
                    help='Publish truthful failed-test metadata for a development candidate; no acceptance gate is opened')
    args=ap.parse_args()
    bad=[]
    for path,value in render(ROOT, allow_incomplete=args.allow_incomplete).items():
        text=json.dumps(value,ensure_ascii=False,indent=2)+'\n'
        if args.check:
            if not path.exists() or path.read_text()!=text:bad.append(str(path.relative_to(ROOT)))
        else:
            # Historical evidence may be shared with a sealed baseline tree.
            # Detach the generated current index before writing through it.
            if path.exists() and path.stat().st_nlink > 1:
                original = path.read_bytes()
                path.unlink()
                path.write_bytes(original)
            path.write_text(text)
    if bad:raise SystemExit('Stale current metadata: '+', '.join(bad))
    print('Current metadata '+('verified' if args.check else 'generated'))
if __name__=='__main__':main()
