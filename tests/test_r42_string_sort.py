class ArchivedStrings(unittest.TestCase):
    def test_all_300_framework_pair_signs(self):
        backend=PortableNLSBackend()
        for row in PROBE['comparisons']:
            with self.subTest(left=row['left'],right=row['right']):
                self.assertEqual(backend.compare(row['left'],row['right'],'ja-JP'),row['sign'])
                self.assertEqual(backend.compare(row['right'],row['left'],'ja-JP'),-row['sign'])

    def test_culturally_equal_different_text_pairs(self):
        for left,right in [('é','e\u0301'),('ß','ss'),('ü','u\u0308')]:
            self.assertNotEqual(left,right)
            self.assertEqual(compare_strings(left,right),0)
        # NLS Japanese diacritic accumulation is not Unicode normalization.
        self.assertEqual(compare_strings('ば','は\u3099'),-1)
        self.assertEqual(compare_strings('ぱ','は\u309a'),-1)

