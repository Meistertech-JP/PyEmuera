class StringSortContracts(Harness):
    def arrays(self,keys,rows=1):
        vm=self.make(headers=f'#DIMS KEYS,{len(keys)}\n#DIM IDX,{len(keys)},{rows}')
        for i,key in enumerate(keys):
            vm.set(f'KEYS:{i}',key)
            for column in range(rows):vm.set(f'IDX:{i}:{column}',i+1+10000*column)
        return vm

    def test_all_source_size_boundaries_ascii_order(self):
        for n in [0,1,2,3,4,15,16,17,23,24,25,31,32,33,65]:
            keys=[f'k{i:03d}' for i in range(n-1,-1,-1)]
            with self.subTest(n=n):
                if n==0:
                    # List.Sort's empty list contract is distinct from the
                    # preserved ERH declaration restriction on zero dimensions.
                    self.assertEqual(framework_list_order([],string=True),[])
                    with self.assertRaises(EraError) as error:self.arrays([])
                    self.assertEqual(error.exception.code,'E_DECLARATION')
                    continue
                vm=self.arrays(keys);self.assertEqual(vm.eval('ARRAYMSORT(KEYS,IDX)'),1)
                self.assertEqual([vm.get(f'KEYS:{i}') for i in range(n)],[f'k{i:03d}' for i in range(n)])
                self.assertEqual([vm.get(f'IDX:{i}:0') for i in range(n)],list(range(n,0,-1)))

    def test_equal_but_different_strings_keep_framework_tie_order(self):
        keys=['é','e\u0301']*12
        expected=[0]+list(range(21,0,-1))+[22,23]
        self.assertEqual(framework_list_order(keys,string=True),expected)
        vm=self.arrays(keys);self.assertEqual(vm.eval('ARRAYMSORT(KEYS,IDX)'),1)
        self.assertEqual([vm.get(f'IDX:{i}:0') for i in range(24)],[i+1 for i in expected])

    def test_two_dimensional_related_rows_follow_culture_order(self):
        vm=self.arrays(['あ','A','a','ｱ'],rows=2)
        self.assertEqual(vm.eval('ARRAYMSORT(KEYS,IDX)'),1)
        self.assertEqual([vm.get(f'IDX:{i}:0') for i in range(4)],[3,2,4,1])
        self.assertEqual([vm.get(f'IDX:{i}:1') for i in range(4)],[10003,10002,10004,10001])

    def test_duplicate_related_array_reapplies_permutation(self):
        vm=self.arrays(['c','a','b'])
        self.assertEqual(vm.eval('ARRAYMSORT(KEYS,IDX,IDX)'),1)
        self.assertEqual([vm.get(f'IDX:{i}:0') for i in range(3)],[3,1,2])

    def test_later_short_array_preserves_prior_culture_writes(self):
        vm=self.make(headers='#DIMS KEYS,3\n#DIM IDX,3\n#DIM SHORT,1\n#DIM AFTER,3')
        for i,key in enumerate(['あ','A','a']):vm.set(f'KEYS:{i}',key);vm.set(f'IDX:{i}',i+1);vm.set(f'AFTER:{i}',i+11)
        self.assertEqual(vm.eval('ARRAYMSORT(KEYS,IDX,SHORT,AFTER)'),0)
        self.assertEqual([vm.get(f'KEYS:{i}') for i in range(3)],['a','A','あ'])
        self.assertEqual([vm.get(f'IDX:{i}') for i in range(3)],[3,2,1])
        self.assertEqual([vm.get(f'AFTER:{i}') for i in range(3)],[11,12,13])

    def test_dynamic_string_subscript_effects_stay_suppressed(self):
        vm=self.arrays(['B','a','b']);vm.set('A',9);rng=vm.rng.getstate()
        self.assertEqual(vm.eval('ARRAYMSORT(KEYS:(++A),IDX:RAND(99):(++A))'),1)
        self.assertEqual(vm.get('A'),9);self.assertEqual(vm.rng.getstate(),rng)

    def test_backend_exception_precedes_any_array_or_result_write(self):
        vm=self.arrays(['d','c','b','a']);vm.set('RESULT',77);vm.set('RESULTS','keep')
        before={n:dict(v.values) for n,v in vm.data.variables.items()};rng=vm.rng.getstate();calls=[]
        def fail(left,right,culture=None):
            calls.append((left,right))
            if len(calls)==3:raise EraError('injected comparison failure',code='E_COLLATION')
            return compare_strings(left,right,culture)
        with patch('pyemuera.collation1824.compare_strings',side_effect=fail):
            with self.assertRaises(EraError) as caught:vm.eval('ARRAYMSORT(KEYS,IDX)')
        self.assertEqual(caught.exception.code,'E_COLLATION');self.assertEqual(len(calls),3)
        self.assertEqual({n:v.values for n,v in vm.data.variables.items()},before)
        self.assertEqual(vm.get('RESULT'),77);self.assertEqual(vm.get('RESULTS'),'keep');self.assertEqual(vm.rng.getstate(),rng)

    def test_utf16_surrogate_units_are_not_scalar_normalized(self):
        self.assertEqual(compare_strings('\U0001f600','\ud83d\ude00'),0)

    def test_explicit_culture_and_backend_are_visible(self):
        metadata=comparison_identity()
        self.assertEqual(metadata['culture'],'ja-JP')
        self.assertIn(metadata['backend'],['portable-ms-nls','windows-nls'])
