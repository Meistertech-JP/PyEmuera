"""Fresh Framework Array.Sort expectations, separate from native ERB evidence.

GenericArraySortHelper traces use a reference IComparable<T> wrapper because
String is sealed. Real string[] outcomes and BACK callbacks are independently
captured. Null identities (-1) and shared empty-string identities (-4) are
explicitly bounded. No expectations are generated by the Python helper.
"""
import gzip
import hashlib
import json
from pathlib import Path
import sys
import unittest
from unittest.mock import patch

import pyemuera.arraysort1824 as module
from pyemuera.collation_portable import PortableNLSBackend
from pyemuera.errors import EraError

FIXTURE = Path(__file__).parent / 'fixtures/r50/arraysort-framework.json.gz'
FIXTURE_SHA256 = '786b18e23289905b25a396657a8f6156337b4b2b08e5f7b743bc6f5367762d40'


def load():
    raw = FIXTURE.read_bytes()
    assert hashlib.sha256(raw).hexdigest() == FIXTURE_SHA256
    return json.loads(gzip.decompress(raw))


def strings(case):
    return [None if h is None else bytes.fromhex(h).decode('utf-16-le', 'surrogatepass')
            for h in case['inputs_utf16le_hex']]


def hexes(values):
    return [None if v is None else v.encode('utf-16-le', 'surrogatepass').hex() for v in values]


class ApplicationFailure(Exception):
    pass


class IndexFailure(Exception):
    pass


class NullReceiver(Exception):
    pass


class Identified(str):
    def __new__(cls, value, index):
        item = super().__new__(cls, value)
        item.index = index
        return item


class ArraySortFrameworkR50(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.data = load()

    def test_measured_population_and_runtime_identity(self):
        data = self.data
        self.assertEqual(data['culture'], 'ja-JP')
        self.assertEqual(data['target_framework'], '.NETFramework,Version=v4.8')
        self.assertEqual(data['framework_release'], 533509)
        self.assertEqual(data['windows_registry_build'], '19045')
        self.assertEqual(len(data['cases']), 266)
        counts = {c['count'] for c in data['cases'] if c['name'].startswith('ascii_reverse_')}
        self.assertEqual(counts, {0, 1, 2, 3, 16, 17, 31, 32, 33, 63, 64, 65})
        known = [c for c in data['cases'] if c['name'].startswith('known44_')]
        self.assertEqual(len(known), 4)
        self.assertTrue(all(c['count'] == 44 for c in known))
        self.assertFalse(data['provenance']['plan_provenance']['new_jamo_search'])

    def test_every_framework_trace_and_partial_temporary_state(self):
        """Replay measured signs, strictly checking receiver/argument identity.

        Includes throwing comparers and out-of-bounds scans. This isolates sort
        mechanics from culture models, including any portable known limits.
        """
        for case in self.data['cases']:
            with self.subTest(case=case['name']):
                values = strings(case)
                items = list(zip(values, range(len(values))))
                position = 0
                back = case['direction'] == 'BACK'

                def identity(item):
                    return -1 if item[0] is None else item[1]

                def compare(left, right):
                    nonlocal position
                    if back:
                        left, right = right, left
                    self.assertLess(position, len(case['calls']), case['name'])
                    expected = case['calls'][position]
                    self.assertEqual(expected['comparison_call_index'], position)
                    self.assertEqual(identity(left), expected['left_original_index'])
                    self.assertEqual(identity(right), expected['right_original_index'])
                    position += 1
                    error = expected['exception']
                    if error:
                        raise {'System.ApplicationException': ApplicationFailure,
                               'System.IndexOutOfRangeException': IndexFailure,
                               'System.NullReferenceException': NullReceiver}[error]()
                    return expected['comparison_sign']

                caught = None
                try:
                    if case['algorithm'] == 'forced_heap':
                        module._heap_sort(items, compare, 0, len(items) - 1,
                                          not back, lambda item: item[0] is None)
                    else:
                        module._sort_in_place(items, compare, comparable=not back,
                                              is_null=lambda item: item[0] is None)
                except (ApplicationFailure, IndexFailure, NullReceiver, module._ArrayBoundsError) as exc:
                    caught = exc
                if caught is None:
                    self.assertIsNone(case['exception'])
                elif isinstance(caught, (IndexFailure, module._ArrayBoundsError)):
                    self.assertEqual(case['exception'], 'System.ArgumentException')
                    self.assertIsNone(case['inner_exception'])
                else:
                    inner = 'System.ApplicationException' if isinstance(caught, ApplicationFailure) else 'System.NullReferenceException'
                    if case['algorithm'] == 'forced_heap':
                        self.assertEqual(case['exception'], inner)
                    else:
                        self.assertEqual(case['exception'], 'System.InvalidOperationException')
                        self.assertEqual(case['inner_exception'], inner)
                self.assertEqual(position, len(case['calls']))
                self.assertEqual([identity(v) for v in items], case['order'])
                self.assertEqual(hexes([v[0] for v in items]), case['temporary_utf16le_hex'])

    def test_traced_reference_path_agrees_with_real_string_arrays(self):
        observed = 0
        for case in self.data['cases']:
            direct = case['direct_string']
            if direct is None:
                continue
            observed += 1
            with self.subTest(case=case['name']):
                self.assertEqual(case['exception'], direct['exception'])
                self.assertEqual(case['inner_exception'], direct['inner_exception'])
                self.assertEqual(case['temporary_utf16le_hex'], direct['temporary_utf16le_hex'])
                # Every observable real string reference has the same identity.
                for actual, tagged in zip(direct['order'], case['order'], strict=True):
                    if actual != -4:
                        self.assertEqual(actual, tagged)
                staged = (case['inputs_utf16le_hex'] if case['exception']
                          else case['temporary_utf16le_hex'])
                self.assertEqual(direct['source_utf16le_hex'], hexes(['outside-left']) + staged + hexes(['outside-right']))
                if case['direction'] == 'BACK':
                    converted = [dict(comparison_call_index=row['comparison_call_index'],
                                      left_utf16le_hex=None if row['left_original_index'] < 0 else case['inputs_utf16le_hex'][row['left_original_index']],
                                      right_utf16le_hex=None if row['right_original_index'] < 0 else case['inputs_utf16le_hex'][row['right_original_index']],
                                      comparison_sign=row['comparison_sign'], exception=row['exception'])
                                 for row in case['calls']]
                    self.assertEqual(converted, direct['calls'])
        self.assertEqual(observed, 194)

    def check_public_backend(self, backend):
        checked = 0
        for case in self.data['cases']:
            if case['algorithm'] != 'public' or case['mode'] != 'culture' or case['throw_at']:
                continue
            checked += 1
            values = [None if s is None else Identified(s, i) for i, s in enumerate(strings(case))]
            before = values.copy()
            calls = []

            def compare(left, right):
                result = backend.compare(left, right, 'ja-JP')
                calls.append((left.index, right.index, result))
                return result

            with self.subTest(case=case['name'], backend=type(backend).__name__), patch('pyemuera.collation1824.compare_strings', compare):
                if case['exception']:
                    with self.assertRaises(EraError):
                        module.framework_array_sort(values, backward=case['direction'] == 'BACK')
                else:
                    actual = module.framework_array_sort(values, backward=case['direction'] == 'BACK')
                    self.assertIsNot(actual, values)
                    self.assertEqual(hexes(actual), case['temporary_utf16le_hex'])
                    self.assertEqual([-1 if v is None else v.index for v in actual], case['order'])
                self.assertEqual(values, before)
                self.assertTrue(all(a is b for a, b in zip(values, before, strict=True)))
                expected = [(r['left_original_index'], r['right_original_index'], r['comparison_sign'])
                            for r in case['calls'] if r['left_original_index'] >= 0 and r['right_original_index'] >= 0]
                self.assertEqual(calls, expected)
        self.assertEqual(checked, 188)

    def test_portable_backend_public_api_order_and_full_comparison_trace(self):
        self.check_public_backend(PortableNLSBackend())

    def test_windows_backend_public_api_order_and_full_comparison_trace(self):
        if sys.platform != 'win32':
            # This cross-platform suite still exercises every case above with
            # the portable backend; Windows-only calls run on the Windows host.
            return
        from pyemuera.collation_windows import WindowsNLSBackend
        self.check_public_backend(WindowsNLSBackend())

    def test_comparison_failures_do_not_modify_input_and_propagate_unchanged(self):
        for n in [3, 16, 17, 33, 65]:
            for back in [False, True]:
                for stop in [1, 3]:
                    original = [f'k{i:03d}' for i in range(n - 1, -1, -1)]
                    before = original.copy()
                    failure = EraError('injected r50 backend failure', code='E_COLLATION')
                    calls = []

                    def fail(left, right):
                        calls.append((left, right))
                        if len(calls) == stop:
                            raise failure
                        return (left > right) - (left < right)

                    with self.subTest(n=n, backward=back, stop=stop):
                        with self.assertRaises(EraError) as error:
                            module.framework_array_sort(original, backward=back, compare=fail)
                        self.assertIs(error.exception, failure)
                        self.assertEqual(original, before)
                        self.assertEqual(len(calls), stop)

    def test_back_is_swapped_comparison_not_reversed_forward_result(self):
        # Framework equal-key permutations are intentionally unstable. Reverse
        # of the FORWARD result would change identities even for two equal keys.
        cases = {c['name']: c for c in self.data['cases']}
        for n in [2, 3, 16, 17, 31, 32, 33, 63, 64, 65]:
            f = cases[f'equal_distinct_{n}_FORWARD']
            b = cases[f'equal_distinct_{n}_BACK']
            self.assertNotEqual(list(reversed(f['order'])), b['order'])

    def test_exact_array_bounds_and_comparable_fallback_differ_from_list(self):
        cases = {c['name']: c for c in self.data['cases']}
        bad = cases['always_negative_17_BACK']
        self.assertEqual(bad['capacity'], 17)
        self.assertEqual(bad['list_comparison']['capacity'], 32)
        self.assertEqual(bad['exception'], 'System.ArgumentException')
        self.assertGreater(len(bad['list_comparison']['calls']), len(bad['calls']))
        attempted = []

        def negative(left, right):
            attempted.append((left, right))
            return -1

        values = [Identified(s, i) for i, s in enumerate(strings(bad))]
        with self.assertRaises(EraError) as caught:
            module.framework_array_sort(values, backward=True, compare=negative)
        self.assertEqual(caught.exception.code, 'E_ARGUMENT')
        self.assertEqual(len(attempted), len(bad['calls']))
        self.assertEqual([v.index for v in values], list(range(17)))

        # This pathological Comparable reaches the actual depth fallback at 65
        # while generic Comparison partitions differently. Framework expected
        # permutations and complete calls were freshly observed, not inferred.
        positive = cases['positive_65_FORWARD']
        self.assertIsNone(positive['exception'])
        self.assertNotEqual(positive['order'], positive['list_comparison']['order'])
        values = [Identified(s, i) for i, s in enumerate(strings(positive))]
        result = module.framework_array_sort(values, compare=lambda a, b: 0 if a.index == b.index else 1)
        self.assertEqual([v.index for v in result], positive['order'])

    def test_no_comparison_for_zero_and_one_and_no_shared_return_array(self):
        for values in [[], ['one'], [None]]:
            with patch('pyemuera.collation1824.compare_strings', side_effect=AssertionError('unexpected comparison')):
                for back in [False, True]:
                    actual = module.framework_array_sort(values, backward=back)
                    self.assertEqual(actual, values)
                    self.assertIsNot(actual, values)


if __name__ == '__main__':
    unittest.main()
